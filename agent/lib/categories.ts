const CATEGORY_BY_SLUG = new Map<string, CategoryDefinition>(
  CATEGORIES.map((category) => [category.slug, category]),
);

export function getCategory(slug: string | null | undefined): CategoryDefinition | undefined {
  if (!slug) return undefined;
  return CATEGORY_BY_SLUG.get(slug);
}

export function isCategorySlug(value: string): value is CategorySlug {
  return CATEGORY_BY_SLUG.has(value);
}

export function categoryLabel(slug: string | null | undefined): string {
  return getCategory(slug)?.label ?? "Otros";
}

export function categoryEmoji(slug: string | null | undefined): string {
  return getCategory(slug)?.emoji ?? "📦";
}
